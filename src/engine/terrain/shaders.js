export var TERRAIN_VERT = [
  'attribute float aAO;',
  'varying vec3 vWorld;',
  'varying vec3 vNormal;',
  'varying float vAO;',
  'void main() {',
  '  vec4 wp = modelMatrix * vec4(position, 1.0);',
  '  vWorld = wp.xyz;',
  '  vNormal = normalize(mat3(modelMatrix) * normal);',
  '  vAO = aAO;',
  '  gl_Position = projectionMatrix * viewMatrix * wp;',
  '}'
].join('\n');

export var TERRAIN_FRAG = [
  'uniform vec3 uSunDir;',
  'uniform vec3 uAmbient;',
  'uniform vec3 uSunCol;',
  'uniform vec3 uFogColor;',
  'uniform float uFogNear;',
  'uniform float uFogFar;',
  'uniform sampler2D uShadowMap;',
  'uniform mat4 uShadowMatrix;',
  'uniform vec2 uShadowMapSize;',
  'uniform float uShadowBias;',
  'uniform float uShadowMix;',
  'varying vec3 vWorld;',
  'varying vec3 vNormal;',
  'varying float vAO;',
  'float hash21(vec2 p) {',
  '  p = fract(p * vec2(123.34, 456.21));',
  '  p += dot(p, p + 45.32);',
  '  return fract(p.x * p.y);',
  '}',
  'float vn2(vec2 p) {',
  '  vec2 i = floor(p);',
  '  vec2 f = fract(p);',
  '  f = f * f * f * (f * (f * 6.0 - 15.0) + 10.0);',
  '  float a = hash21(i), b = hash21(i + vec2(1.0, 0.0));',
  '  float c = hash21(i + vec2(0.0, 1.0)), e = hash21(i + vec2(1.0, 1.0));',
  '  return mix(mix(a, b, f.x), mix(c, e, f.x), f.y);',
  '}',
  'float fbm2(vec2 p) {',
  '  return vn2(p) * 0.50',
  '       + vn2(p * 2.13 + 1.7) * 0.28',
  '       + vn2(p * 4.37 - 2.1) * 0.15',
  '       + vn2(p * 8.91 + 0.4) * 0.07;',
  '}',
  'float ridge2(vec2 p) {',
  '  float n = 1.0 - abs(2.0 * vn2(p) - 1.0);',
  '  return n * n;',
  '}',
  /* Three.js packs shadow depth into RGBA — must unpack, not read .r */
  'const float UnpackDownscale = 255.0 / 256.0;',
  'const vec4 UnpackFactors4 = vec4(',
  '  UnpackDownscale / 1.0,',
  '  UnpackDownscale / 256.0,',
  '  UnpackDownscale / 65536.0,',
  '  1.0 / 16777216.0',
  ');',
  'float unpackShadowDepth(vec4 v) { return dot(v, UnpackFactors4); }',
  'float shadowSample(vec2 uv, float depth) {',
  '  return step(depth, unpackShadowDepth(texture2D(uShadowMap, uv)));',
  '}',
  /* Soft bilinear sample — interpolates across shadow-map texels to hide staircasing. */
  'float shadowSampleBilinear(vec2 uv, float depth) {',
  '  vec2 size = uShadowMapSize;',
  '  vec2 texel = 1.0 / size;',
  '  vec2 uvTex = uv * size - 0.5;',
  '  vec2 base = (floor(uvTex) + 0.5) * texel;',
  '  vec2 f = fract(uvTex);',
  '  float s00 = shadowSample(base, depth);',
  '  float s10 = shadowSample(base + vec2(texel.x, 0.0), depth);',
  '  float s01 = shadowSample(base + vec2(0.0, texel.y), depth);',
  '  float s11 = shadowSample(base + texel, depth);',
  '  return mix(mix(s00, s10, f.x), mix(s01, s11, f.x), f.y);',
  '}',
  'float terrainShadow(vec3 worldPos) {',
  '  if (uShadowMix < 0.05) return 1.0;',
  '  vec4 sc = uShadowMatrix * vec4(worldPos, 1.0);',
  '  vec3 p = sc.xyz / sc.w;',
  '  if (p.x < 0.0 || p.x > 1.0 || p.y < 0.0 || p.y > 1.0 || p.z < 0.0 || p.z > 1.0) return 1.0;',
  '  float depth = p.z - uShadowBias;',
  '  vec2 texel = 1.0 / uShadowMapSize;',
  '  /* Rotated Poisson disk softens tree silhouette; radius in shadow-map texels. */',
  '  float ang = hash21(floor(vWorld.xz * 8.0)) * 6.2831853;',
  '  float ca = cos(ang), sa = sin(ang);',
  '  mat2 rot = mat2(ca, -sa, sa, ca);',
  '  float radius = 2.5;',
  '  float occ = 0.0;',
  '  occ += shadowSampleBilinear(p.xy, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2(-0.326, -0.406) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2(-0.840, -0.074) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2(-0.696,  0.457) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2(-0.203,  0.621) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2( 0.962, -0.195) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2( 0.473, -0.480) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2( 0.519,  0.767) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2( 0.185, -0.893) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2( 0.507,  0.064) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2( 0.896,  0.412) * texel * radius, depth);',
  '  occ += shadowSampleBilinear(p.xy + rot * vec2(-0.322, -0.933) * texel * radius, depth);',
  '  return occ / 12.0;',
  '}',
  'void main() {',
  '  vec3 n = normalize(vNormal);',
  '  vec2 wUV = vWorld.xz;',
  '  float h = vWorld.y;',
  '  float slope = 1.0 - n.y;',
  '  float detail = vn2(wUV * 1.1) * 0.60',
  '               + vn2(wUV * 4.2) * 0.32',
  '               + ridge2(wUV * 0.55) * 0.08;',
  '  float vary = vn2(wUV * 0.045);',
  '  float rockAmt = smoothstep(0.26, 0.44, slope + (detail - 0.5) * 0.10);',
  '  float nb = vn2(wUV * 2.4);',
  '  vec3 pn = vec3(',
  '    vn2(wUV * 2.4 + vec2(0.31, 0.0)) - nb,',
  '    0.0,',
  '    vn2(wUV * 2.4 + vec2(0.0, 0.31)) - nb',
  '  );',
  '  float nb2 = vn2(wUV * 7.5);',
  '  vec3 pn2 = vec3(',
  '    vn2(wUV * 7.5 + vec2(0.17, 0.0)) - nb2,',
  '    0.0,',
  '    vn2(wUV * 7.5 + vec2(0.0, 0.17)) - nb2',
  '  );',
  '  n = normalize(n + pn * 2.8 * rockAmt + pn2 * (0.55 + 1.4 * rockAmt));',
  '  vec3 colSea = vec3(0.13, 0.22, 0.21);',
  '  /* beach — wet sand, ripples, shell speckles, tide stains */',
  '  float wetSand = 1.0 - smoothstep(-0.2, 2.6, h);',
  '  float sandRipple = sin(dot(wUV, vec2(0.82, 0.18)) * 3.4 + fbm2(wUV * 0.55) * 5.0) * 0.5 + 0.5;',
  '  float sandSpeck = step(0.91, vn2(wUV * 22.0)) * step(0.87, vn2(wUV * 29.0 + 4.3));',
  '  float tideStain = smoothstep(1.9, 0.15, h) * smoothstep(0.30, 0.72, vn2(wUV * 0.20 + 2.1));',
  '  vec3 sandDry = vec3(0.84, 0.76, 0.54);',
  '  vec3 sandWarm = vec3(0.74, 0.64, 0.44);',
  '  vec3 sandWet = vec3(0.48, 0.44, 0.36);',
  '  vec3 colSand = mix(sandWarm, sandDry, sandRipple * 0.42 + vn2(wUV * 0.065) * 0.28);',
  '  colSand = mix(colSand, sandWet, wetSand * 0.72);',
  '  colSand = mix(colSand, vec3(0.58, 0.54, 0.44), tideStain * 0.45);',
  '  colSand += vec3(0.05, 0.04, 0.03) * sandSpeck;',
  '  colSand *= 0.90 + 0.20 * sandRipple;',
  '  /* grassland — meadow patches, dry tufts, dirt, moist hollows */',
  '  float grassPatch = vn2(wUV * 0.038);',
  '  float grassDry = vn2(wUV * 0.10 + 3.4);',
  '  float grassBlade = vn2(wUV * 9.2) * 0.55 + vn2(wUV * 18.5) * 0.45;',
  '  float grassDirt = smoothstep(0.66, 0.84, fbm2(wUV * 0.13 + 1.1));',
  '  float grassFlower = smoothstep(0.78, 0.92, vn2(wUV * 0.19 + 8.2));',
  '  vec3 grassLush = vec3(0.20, 0.40, 0.15);',
  '  vec3 grassBright = vec3(0.36, 0.54, 0.22);',
  '  vec3 grassDryCol = vec3(0.44, 0.50, 0.24);',
  '  vec3 grassDirtCol = vec3(0.32, 0.26, 0.17);',
  '  vec3 grassMoss = vec3(0.16, 0.32, 0.18);',
  '  vec3 colGrass = mix(grassLush, grassBright, grassPatch);',
  '  colGrass = mix(colGrass, grassDryCol, smoothstep(0.55, 0.76, grassDry) * 0.38);',
  '  colGrass = mix(colGrass, grassDirtCol, grassDirt * 0.58);',
  '  colGrass = mix(colGrass, grassMoss, (1.0 - vAO) * 0.30);',
  '  colGrass = mix(colGrass, vec3(0.52, 0.48, 0.22), grassFlower * 0.12);',
  '  colGrass *= 0.90 + 0.18 * grassBlade;',
  '  /* coastal dune grass at sand-to-plains transition */',
  '  float duneGrass = smoothstep(1.2, 2.8, h) * (1.0 - smoothstep(3.2, 4.8, h));',
  '  colGrass = mix(colGrass, mix(colSand, colGrass, 0.55), duneGrass * 0.35);',
  '  float rockVein = ridge2(wUV * 0.85 + 2.1) * 0.35 + vn2(wUV * 6.0) * 0.65;',
  '  vec3 colRock = mix(vec3(0.34, 0.33, 0.32), vec3(0.50, 0.48, 0.46), vary);',
  '  colRock = mix(colRock, vec3(0.28, 0.27, 0.26), rockVein * 0.22);',
  '  colRock *= 0.88 + 0.24 * detail;',
  '  /* snow — drifts, wind streaks, blue shadows, sparkle */',
  '  float snowLine = smoothstep(33.0, 39.5, h + (detail - 0.5) * 4.0) * (1.0 - smoothstep(0.22, 0.48, slope));',
  '  float snowDrift = fbm2(wUV * 0.055);',
  '  float snowStreak = vn2(vec2(dot(wUV, vec2(0.86, 0.50)) * 0.11, wUV.y * 0.035 + 1.3));',
  '  float snowSparkle = step(0.962, vn2(wUV * 36.0 + floor(vn2(wUV * 2.8) * 14.0)));',
  '  vec3 snowFresh = vec3(0.94, 0.96, 0.99);',
  '  vec3 snowShadow = vec3(0.76, 0.84, 0.94);',
  '  vec3 snowDirty = vec3(0.84, 0.87, 0.90);',
  '  vec3 colSnow = mix(snowFresh, snowShadow, (1.0 - vAO) * 0.40 + slope * 0.22);',
  '  colSnow = mix(colSnow, snowDirty, snowStreak * 0.22 + snowDrift * 0.14);',
  '  colSnow *= 0.95 + 0.10 * snowDrift;',
  '  vec3 col = mix(colSea, colSand, smoothstep(-1.8, 0.5, h));',
  '  col = mix(col, colGrass, smoothstep(1.0, 3.6, h));',
  '  col = mix(col, colRock, rockAmt);',
  '  col = mix(col, colSnow, snowLine);',
  '  col *= 0.84 + 0.30 * detail;',
  '  float diff = max(dot(n, uSunDir), 0.0);',
  '  diff = pow(diff, 1.12);',
  '  float wrap = max(dot(n, uSunDir) * 0.5 + 0.5, 0.0);',
  '  vec3 light = uAmbient * (0.72 + 0.28 * wrap) + uSunCol * diff * 1.38;',
  '  vec3 view = normalize(cameraPosition - vWorld);',
  '  vec3 hv = normalize(uSunDir + view);',
  '  float spec = pow(max(dot(n, hv), 0.0), 56.0);',
  '  float rockSpec = rockAmt * pow(max(dot(n, hv), 0.0), 22.0) * 0.14;',
  '  float specAmt = 0.55 * snowLine + 0.22 * wetSand + 0.12 * smoothstep(0.5, -0.5, h);',
  '  vec3 c = col * vAO * light + (spec * specAmt + rockSpec) * uSunCol * 1.3;',
  '  c += snowSparkle * snowLine * diff * uSunCol * 0.35;',
  '  float sh = terrainShadow(vWorld);',
  '  c *= mix(1.0, mix(0.42, 1.0, sh), uShadowMix);',
  '  float fog = smoothstep(uFogNear, uFogFar, length(cameraPosition - vWorld));',
  '  c = mix(c, uFogColor, fog);',
  '  gl_FragColor = vec4(c, 1.0);',
  '}'
].join('\n');
