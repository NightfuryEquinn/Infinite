export var WATER_VERT = [
  'uniform float uTime;',
  'uniform vec2 uFloorOrigin;',
  'uniform float uFloorSize;',
  'uniform sampler2D uFloorMap;',
  'varying vec3 vWorld;',
  'varying float vWave;',
  'varying float vOcean;',
  'varying vec2 vFloorUV;',
  'void main() {',
  '  vec4 wp = modelMatrix * vec4(position, 1.0);',
  '  vec2 p = wp.xz;',
  '  vFloorUV = (p - uFloorOrigin) / uFloorSize;',
  '  float ocean = texture2D(uFloorMap, clamp(vFloorUV, 0.001, 0.999)).g;',
  '  float w1 = sin(p.x * 0.055 + uTime * 1.10) * 0.18;',
  '  float w2 = cos(p.y * 0.075 + uTime * 1.45) * 0.14;',
  '  float w3 = sin(dot(p, vec2(0.04, 0.06)) + uTime * 0.85) * 0.10;',
  '  float w4 = cos(p.x * 0.19 - p.y * 0.13 + uTime * 2.10) * 0.05;',
  '  float wave = (w1 + w2 + w3 + w4) * ocean;',
  '  wp.y += wave;',
  '  vWave = wave;',
  '  vOcean = ocean;',
  '  vWorld = wp.xyz;',
  '  gl_Position = projectionMatrix * viewMatrix * wp;',
  '}'
].join('\n');

export var WATER_FRAG = [
  'uniform float uTime;',
  'uniform float uLightI;',
  'uniform float uSeaLevel;',
  'uniform float uFloorMin;',
  'uniform float uFloorMax;',
  'uniform vec3 uSunDir;',
  'uniform vec3 uFogColor;',
  'uniform float uFogNear;',
  'uniform float uFogFar;',
  'uniform sampler2D uFloorMap;',
  'varying vec3 vWorld;',
  'varying float vWave;',
  'varying float vOcean;',
  'varying vec2 vFloorUV;',
  'float hash21(vec2 p) { p = fract(p * vec2(123.34, 456.21)); p += dot(p, p + 45.32); return fract(p.x * p.y); }',
  'float vn2(vec2 p) {',
  '  vec2 i = floor(p); vec2 f = fract(p); f = f * f * (3.0 - 2.0 * f);',
  '  float a = hash21(i), b = hash21(i + vec2(1.0, 0.0));',
  '  float c = hash21(i + vec2(0.0, 1.0)), e = hash21(i + vec2(1.0, 1.0));',
  '  return mix(mix(a, b, f.x), mix(c, e, f.x), f.y);',
  '}',
  'void main() {',
  '  vec2 p = vWorld.xz;',
  '  float t = uTime;',
  '  float ocean = vOcean;',
  '  float lake = 1.0 - ocean;',
  '  /* Ocean: animated chop. Lakes/ponds: flat, still surface. */',
  '  float dx = (cos(p.x * 0.055 + t * 1.10) * 0.26 + cos(p.x * 0.21 + p.y * 0.11 + t * 2.20) * 0.09) * ocean;',
  '  float dz = (-sin(p.y * 0.075 + t * 1.45) * 0.26 + cos(p.y * 0.17 - p.x * 0.07 + t * 1.90) * 0.09) * ocean;',
  '  dx += cos(p.x * 0.38 - p.y * 0.29 + t * 2.8) * 0.04 * ocean;',
  '  dz += sin(p.x * 0.31 + p.y * 0.42 - t * 2.3) * 0.04 * ocean;',
  '  dx += (vn2(p * 0.45) - 0.5) * 0.04 * lake;',
  '  dz += (vn2(p * 0.45 + 3.1) - 0.5) * 0.04 * lake;',
  '  vec3 n = normalize(vec3(-dx, 1.0, -dz));',
  '  vec3 view = normalize(cameraPosition - vWorld);',
  '  vec4 floorS = texture2D(uFloorMap, clamp(vFloorUV, 0.001, 0.999));',
  '  float floorH = mix(uFloorMin, uFloorMax, floorS.r);',
  '  float depth = max(0.0, uSeaLevel - floorH);',
  '  vec3 deepNavy = vec3(0.02, 0.12, 0.26);',
  '  vec3 midTeal = vec3(0.04, 0.30, 0.40);',
  '  vec3 shallowTurq = vec3(0.07, 0.58, 0.54);',
  '  vec3 seaGlass = vec3(0.12, 0.68, 0.52);',
  '  vec3 sandTint = vec3(0.74, 0.68, 0.50);',
  '  /* Still inland water — greener, quieter */',
  '  vec3 pondDeep = vec3(0.04, 0.18, 0.14);',
  '  vec3 pondMid = vec3(0.06, 0.32, 0.22);',
  '  vec3 pondShallow = vec3(0.14, 0.42, 0.28);',
  '  float depthT = smoothstep(0.4, 16.0, depth);',
  '  vec3 colOcean = mix(seaGlass, shallowTurq, smoothstep(0.0, 3.0, depth));',
  '  colOcean = mix(colOcean, midTeal, smoothstep(1.5, 8.0, depth));',
  '  colOcean = mix(colOcean, deepNavy, depthT);',
  '  colOcean = mix(sandTint * 0.55 + colOcean * 0.45, colOcean, smoothstep(0.0, 2.8, depth));',
  '  vec3 colLake = mix(pondShallow, pondMid, smoothstep(0.0, 2.5, depth));',
  '  colLake = mix(colLake, pondDeep, smoothstep(2.0, 8.0, depth));',
  '  vec3 col = mix(colLake, colOcean, ocean);',
  '  /* soft caustic bands — ocean only */',
  '  vec2 cuv = p * 0.28;',
  '  float caust = (vn2(cuv + t * 0.06) * 0.55 + vn2(cuv * 2.1 - t * 0.04) * 0.45);',
  '  caust = smoothstep(0.42, 0.82, caust) * smoothstep(5.0, 0.15, depth) * ocean;',
  '  col += vec3(0.06, 0.18, 0.14) * caust * 0.22 * uLightI;',
  '  float sss = exp(-depth * 0.32) * (1.0 - depthT);',
  '  col += vec3(0.04, 0.26, 0.20) * sss * mix(0.28, 0.50, ocean);',
  '  col *= mix(0.34, 1.0, uLightI);',
  '  float crest = smoothstep(0.12, 0.28, vWave + abs(dFdx(vWave)) * 2.0 + abs(dFdy(vWave)) * 2.0) * ocean;',
  '  float shore = smoothstep(3.2, 0.25, depth);',
  '  float foam = max(crest * 0.65, shore * mix(0.22, 0.55, ocean));',
  '  foam = smoothstep(0.22, 0.58, foam);',
  '  col = mix(col, mix(vec3(0.70, 0.82, 0.68), vec3(0.88, 0.92, 0.90), ocean), foam * mix(0.28, 0.55, ocean));',
  '  float fres = pow(1.0 - max(dot(n, view), 0.0), 3.2);',
  '  col = mix(col, uFogColor * 0.88 + vec3(0.06, 0.10, 0.14), fres * mix(0.42, 0.62, ocean));',
  '  vec3 hv = normalize(uSunDir + view);',
  '  float spec = pow(max(dot(n, hv), 0.0), mix(96.0, 48.0, ocean));',
  '  col += spec * vec3(0.85, 0.90, 0.88) * mix(0.18, 0.35, ocean) * uLightI;',
  '  float fog = smoothstep(uFogNear, uFogFar, length(cameraPosition - vWorld));',
  '  col = mix(col, uFogColor, fog);',
  '  float alpha = mix(0.70, 0.90, depthT);',
  '  alpha = mix(alpha, 0.82, foam * 0.35);',
  '  alpha = mix(mix(0.78, 0.92, depthT), alpha, ocean);',
  '  gl_FragColor = vec4(col, alpha);',
  '}'
].join('\n');
